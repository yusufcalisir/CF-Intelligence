# ── Sanctions & PEP Screening Compatibility Models ───────────────────────────

class OpenAMLScreeningCheckRequest(BaseModel):
    """Screening search payload targeting a registered person or ad-hoc subject."""
    model_config = ConfigDict(extra="ignore")

    person_id: str | None = None
    target_name: str | None = None
    date_of_birth: str | None = None
    nationality: str | None = None
    threshold: float = Field(default=0.75, ge=0.50, le=1.00)
    lists_to_check: list[str] = Field(
        default_factory=lambda: ["UN", "EU_CFSP", "OFAC_SDN", "PEP"],
        description="Filter specific lists (UN, EU_CFSP, OFAC_SDN, PEP, GOODLIST)",
    )

    @model_validator(mode="before")
    @classmethod
    def _coerce_screening_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "query_name" in data and not data.get("target_name"):
                data["target_name"] = data["query_name"]
            if "match_threshold" in data:
                mt = float(data["match_threshold"])
                if mt > 1.0:
                    data["threshold"] = min(1.0, max(0.50, mt / 100.0))
                else:
                    data["threshold"] = min(1.0, max(0.50, mt))
        return data


