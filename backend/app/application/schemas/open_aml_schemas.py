"""Enterprise Open AML Adapter Pydantic v2 Schemas (Phase 110).

Drop-in API compatibility schemas implementing standard European / International
AML OpenAPI specifications for:
- Person / Legal Entity ingestion and UBO corporate hierarchy
- Real-time online transaction monitoring checks and offline scenario runs
- High-throughput fuzzy Sanctions & PEP screening searches
- Webhook dispatch envelopes and verification payloads
"""

from __future__ import annotations

import secrets
import uuid
from datetime import UTC, datetime
from decimal import Decimal
from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

# ── Enumerations ─────────────────────────────────────────────────────────────

class PersonType(str, Enum):
    """Subject legal classification."""
    INDIVIDUAL = "INDIVIDUAL"
    LEGAL_ENTITY = "LEGAL_ENTITY"


class PersonStatus(str, Enum):
    """Subject compliance lifecycle status."""
    ACTIVE = "ACTIVE"
    BLOCKED = "BLOCKED"
    UNDER_REVIEW = "UNDER_REVIEW"
    INACTIVE = "INACTIVE"


class DocumentType(str, Enum):
    """Identity or corporate registration document type."""
    PASSPORT = "PASSPORT"
    NATIONAL_ID = "NATIONAL_ID"
    DRIVING_LICENSE = "DRIVING_LICENSE"
    RESIDENCE_PERMIT = "RESIDENCE_PERMIT"
    CERTIFICATE_OF_INCORPORATION = "CERTIFICATE_OF_INCORPORATION"
    ARTICLES_OF_ASSOCIATION = "ARTICLES_OF_ASSOCIATION"
    TAX_IDENTIFIER = "TAX_IDENTIFIER"
    OTHER = "OTHER"


class MonitoringMode(str, Enum):
    """Execution mode for AML transaction monitoring."""
    ONLINE = "ONLINE"    # Synchronous blocking/allowing real-time evaluation (<50ms)
    OFFLINE = "OFFLINE"  # Asynchronous background batch/scenario audit


class MonitoringAction(str, Enum):
    """Actionable compliance decision resulting from transaction monitoring."""
    ALLOW = "ALLOW"
    REVIEW = "REVIEW"
    BLOCK = "BLOCK"


class OpenAMLScreeningDisposition(str, Enum):
    """Decision category for screening searches."""
    CLEAR = "CLEAR"
    POTENTIAL_MATCH = "POTENTIAL_MATCH"
    MATCH = "MATCH"


class OpenAMLWebhookEventType(str, Enum):
    """Event types generated by the Open AML adapter pipeline."""
    ALERT_CREATED = "ALERT_CREATED"
    ALERT_STATUS_UPDATED = "ALERT_STATUS_UPDATED"
    SCREENING_ALERT_CREATED = "SCREENING_ALERT_CREATED"
    FINAL_RISK_UPDATED = "FINAL_RISK_UPDATED"


# ── Reusable Component Models ────────────────────────────────────────────────

class Address(BaseModel):
    """Standardized physical address model."""
    model_config = ConfigDict(extra="ignore")

    street: str | None = None
    building_number: str | None = None
    postal_code: str | None = None
    city: str | None = None
    state: str | None = None
    country: str = Field(..., min_length=2, max_length=2, description="ISO 3166-1 alpha-2 country code")

    @field_validator("country")
    @classmethod
    def normalize_country(cls, v: str) -> str:
        return v.strip().upper()


class Document(BaseModel):
    """Identification or verification document model."""
    model_config = ConfigDict(extra="ignore")

    document_type: DocumentType = DocumentType.PASSPORT
    document_number: str = Field(..., min_length=1, max_length=64)
    issuing_country: str = Field("DE", min_length=2, max_length=2)
    issue_date: str | None = None
    expiry_date: str | None = None

    @field_validator("issuing_country")
    @classmethod
    def normalize_country(cls, v: str) -> str:
        return v.strip().upper()


class UBORecord(BaseModel):
    """Ultimate Beneficial Owner or key corporate principal relation."""
    model_config = ConfigDict(extra="ignore")

    ubo_person_id: str = Field(default_factory=lambda: f"UBO-{uuid.uuid4().hex[:8].upper()}", description="Unique person_id of the beneficial owner")
    ubo_name: str = Field(default="", description="Full legal name of the natural person UBO")
    ownership_percentage: float = Field(..., ge=0.0, le=100.0, description="Direct or indirect equity/voting percentage")
    relationship_type: str = Field("BENEFICIAL_OWNER", description="SHAREHOLDER, DIRECTOR, BENEFICIAL_OWNER, TRUSTEE")
    is_pep: bool = Field(default=False, description="Politically Exposed Person flag")
    country_of_residence: str | None = Field(default=None, max_length=2)

    @model_validator(mode="before")
    @classmethod
    def _coerce_ubo_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "full_name" in data and not data.get("ubo_name"):
                data["ubo_name"] = data["full_name"]
            if "name" in data and not data.get("ubo_name"):
                data["ubo_name"] = data["name"]
        return data


# ── Person Ingestion Models ──────────────────────────────────────────────────

class PersonCreateRequest(BaseModel):
    """Drop-in request to register an individual customer or legal entity."""
    model_config = ConfigDict(extra="ignore")

    person_id: str = Field(default_factory=lambda: f"PER-{uuid.uuid4().hex[:12].upper()}", max_length=128, description="Institution-unique customer identifier")
    person_type: PersonType = Field(default=PersonType.INDIVIDUAL)
    first_name: str | None = None
    last_name: str | None = None
    legal_name: str | None = None
    registration_number: str | None = None
    date_of_birth: str | None = None
    nationality: str | None = Field(default=None, max_length=2)
    country_of_residence: str | None = Field(default=None, max_length=2)
    addresses: list[Address] = Field(default_factory=list)
    documents: list[Document] = Field(default_factory=list)
    ubo_records: list[UBORecord] = Field(default_factory=list)
    email: str | None = None
    phone: str | None = None
    client_status: PersonStatus = Field(default=PersonStatus.ACTIVE)
    metadata: dict[str, Any] = Field(default_factory=dict)

    @model_validator(mode="before")
    @classmethod
    def _coerce_person_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "company_name" in data and not data.get("legal_name"):
                data["legal_name"] = data["company_name"]
            if "ubos" in data and not data.get("ubo_records"):
                data["ubo_records"] = data["ubos"]
            if "status" in data and not data.get("client_status"):
                data["client_status"] = data["status"]
        return data

    @field_validator("nationality", "country_of_residence")
    @classmethod
    def normalize_country_opt(cls, v: str | None) -> str | None:
        if v:
            return v.strip().upper()
        return v

    def resolved_display_name(self) -> str:
        """Derive authoritative display name across Individual and Legal Entity schemas."""
        if self.person_type == PersonType.LEGAL_ENTITY and self.legal_name:
            return self.legal_name.strip()
        parts = [p for p in (self.first_name, self.last_name) if p and p.strip()]
        if parts:
            return " ".join(parts).strip()
        return self.legal_name or self.person_id


