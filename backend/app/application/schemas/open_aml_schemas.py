# ── Transaction & Monitoring Check Models ────────────────────────────────────

class PersonTransactionCreateRequest(BaseModel):
    """Standardized transaction ingestion associated with a registered person."""
    model_config = ConfigDict(extra="ignore")

    transaction_id: str = Field(default_factory=lambda: f"TX-{uuid.uuid4().hex[:12].upper()}", max_length=128)
    amount: Decimal = Field(..., gt=Decimal("0.0"), description="Transaction value in specified currency")
    currency: str = Field(default="EUR", min_length=3, max_length=3)
    direction: str = Field(default="OUTBOUND", description="INBOUND or OUTBOUND")
    counterparty_name: str = Field(default="UNKNOWN_COUNTERPARTY", max_length=256)
    counterparty_account: str = Field(default="UNKNOWN_ACCOUNT", max_length=128)
    counterparty_bank_bic: str | None = None
    counterparty_country: str | None = Field(default=None, max_length=2)
    payment_method: str = Field(default="SEPA_INSTANT", description="SEPA_INSTANT, WIRE, CARD, ACH, CRYPTO")
    reference: str | None = None
    merchant_category: str | None = None
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))

    @model_validator(mode="before")
    @classmethod
    def _coerce_txn_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "external_transaction_id" in data and not data.get("transaction_id"):
                data["transaction_id"] = data["external_transaction_id"]
            if "counterparty_iban" in data and not data.get("counterparty_account"):
                data["counterparty_account"] = data["counterparty_iban"]
            if "beneficiary_country" in data and not data.get("counterparty_country"):
                data["counterparty_country"] = data["beneficiary_country"]
        return data

    @field_validator("currency", "counterparty_country")
    @classmethod
    def normalize_upper(cls, v: str | None) -> str | None:
        if v:
            return v.strip().upper()
        return v


