    @classmethod
    def generate_fincen_sar_xml(
        cls,
        case_id: str,
        reporting_institution: str = "Consortium AML Joint Investigation Unit",
        tin_type: str = "EIN",
        activity_status: str = "CONFIRMED_FRAUD",
        total_risk_score: float = 850.0,
        priority: str = "CRITICAL",
        summary: str = "Automated cross-bank coordinated mule layering pattern detected via federated intelligence.",
        subjects: list[str] | None = None,
        alert_ids: list[str] | None = None,
        notes: list[dict[str, str]] | None = None,
        timeline: list[dict[str, str]] | None = None,
        classification: ExportClassification = ExportClassification.PROTOTYPE_EXPORT,
        validate: bool = True,
    ) -> tuple[str, RegulatoryValidationReport]:
        """Generate schema-conforming FinCEN BSA 2.0 SAR XML with prototype regulatory framing."""
        if not case_id or not case_id.strip():
            raise MissingRegulatoryFieldError("case_id is required for FinCEN SAR generation")

        root = ET.Element(
            "EFilingSubmission",
            {
                "xmlns": "http://www.fincen.gov/spec/bsa",
                "xmlns:xsi": "http://www.w3.org/2001/XMLSchema-instance",
                "xsi:schemaLocation": "http://www.fincen.gov/spec/bsa FinCEN_SAR_2.0.xsd",
            },
        )

        # Header
        header = ET.SubElement(root, "SubmissionHeader")
        ET.SubElement(header, "ActivityType").text = "SAR"
        ET.SubElement(header, "SubmissionType").text = "New"
        ET.SubElement(header, "CreatedTimestamp").text = datetime.now(UTC).isoformat()

        # Activity
        activity = ET.SubElement(root, "Activity")
        ET.SubElement(activity, "ActivityID").text = case_id
        ET.SubElement(activity, "ActivityStatus").text = activity_status

        inst = ET.SubElement(activity, "ReportingInstitution")
        ET.SubElement(inst, "InstitutionName").text = reporting_institution
        ET.SubElement(inst, "TINType").text = tin_type

        # Subjects
        subjects_elem = ET.SubElement(activity, "Subjects")
        subj_hashes = subjects or [f"hash_subj_{hashlib.sha256(case_id.encode()).hexdigest()[:32]}"]
        for sh in sorted(subj_hashes):
            s_elem = ET.SubElement(subjects_elem, "Subject")
            ET.SubElement(s_elem, "EntityPrivacyHash").text = sh

        # Suspicious Activity Details
        details = ET.SubElement(activity, "SuspiciousActivityDetails")
        ET.SubElement(details, "TotalRiskScore").text = f"{total_risk_score:.2f}"
        ET.SubElement(details, "Priority").text = priority

        alerts_elem = ET.SubElement(details, "AlertIds")
        for aid in sorted(alert_ids or [f"ALERT-{case_id}"]):
            ET.SubElement(alerts_elem, "AlertId").text = aid

        # Narrative
        narrative = ET.SubElement(activity, "Narrative")
        ET.SubElement(narrative, "Summary").text = summary

        if notes:
            notes_elem = ET.SubElement(narrative, "Notes")
            for n in notes:
                ne = ET.SubElement(notes_elem, "Note")
                ET.SubElement(ne, "Author").text = n.get("author", "AML_INVESTIGATOR")
                ET.SubElement(ne, "Content").text = n.get("content", "")
                ET.SubElement(ne, "Timestamp").text = n.get("timestamp", datetime.now(UTC).isoformat())

        if timeline:
            timeline_elem = ET.SubElement(narrative, "Timeline")
            for e in timeline:
                ee = ET.SubElement(timeline_elem, "Event")
                ET.SubElement(ee, "Type").text = e.get("event_type", "AUDIT")
                ET.SubElement(ee, "Description").text = e.get("description", "")
                ET.SubElement(ee, "Actor").text = e.get("actor", "system")
                ET.SubElement(ee, "Timestamp").text = e.get("timestamp", datetime.now(UTC).isoformat())

        raw_xml = ET.tostring(root, encoding="utf-8").decode("utf-8")
        parsed = defusedxml.minidom.parseString(raw_xml)
        pretty_xml = parsed.toprettyxml(indent="  ")

        report = cls.validate_xml(
            pretty_xml,
            RegulatoryFramework.FINCEN_SAR_2_0,
            classification=classification,
            raise_on_error=validate,
        )
        return pretty_xml, report

    @classmethod
    def generate_goaml_sar_xml(
        cls,
        rentity_id: str,
        entity_reference: str,
        report_code: str = "SAR",
        submission_code: str = "E",
        rentity_branch: str = "CENTRAL_COMPLIANCE",
        reporting_user: str = "COMPLIANCE_OFFICER_01",
        reason: str = "Suspicious structuring and anomalous cross-border payment bursts detected.",
        action_taken: str = "Accounts frozen, enhanced due diligence filed.",
        currency_code: str = "EUR",
        transactions: list[dict[str, Any]] | None = None,
        legal_basis: dict[str, str] | None = None,
        fiu_ref_number: str | None = None,
        classification: ExportClassification = ExportClassification.PROTOTYPE_EXPORT,
        validate: bool = True,
    ) -> tuple[str, RegulatoryValidationReport]:
        """Generate official UNODC goAML 4.0 XML report adhering strictly to schema specifications."""
        if not rentity_id or not rentity_id.strip():
            raise MissingRegulatoryFieldError("rentity_id is mandatory for UNODC goAML filings")
        if not entity_reference or not entity_reference.strip():
            raise MissingRegulatoryFieldError("entity_reference is mandatory for UNODC goAML filings")

        root = ET.Element("report")
        ET.SubElement(root, "rentity_id").text = rentity_id
        ET.SubElement(root, "rentity_branch").text = rentity_branch
        ET.SubElement(root, "submission_code").text = submission_code
        ET.SubElement(root, "report_code").text = report_code
        ET.SubElement(root, "entity_reference").text = entity_reference
        if fiu_ref_number:
            ET.SubElement(root, "fiu_ref_number").text = fiu_ref_number

        ET.SubElement(root, "report_date").text = datetime.now(UTC).isoformat()
        ET.SubElement(root, "currency_code_local").text = currency_code
        ET.SubElement(root, "reporting_user").text = reporting_user
        ET.SubElement(root, "reason").text = reason
        ET.SubElement(root, "action").text = action_taken

        # Legal basis block
        lb = legal_basis or {
            "legal_basis_type": "AMLD6_ART_33",
            "regulatory_framework": "Directive (EU) 2018/1673 & AMLD6",
            "article_reference": "Article 33(1)",
            "legitimate_interest_justification": "Consortium financial crime intelligence sharing under GDPR 6(1)(f)",
            "reporting_entity_role": "CREDIT_INSTITUTION",
        }
        lb_elem = ET.SubElement(root, "legal_basis")
        ET.SubElement(lb_elem, "legal_basis_type").text = lb.get("legal_basis_type", "AMLD6_ART_33")
        ET.SubElement(lb_elem, "regulatory_framework").text = lb.get("regulatory_framework", "AMLD6")
        ET.SubElement(lb_elem, "article_reference").text = lb.get("article_reference", "Article 33")
        ET.SubElement(lb_elem, "legitimate_interest_justification").text = lb.get("legitimate_interest_justification", "")
        ET.SubElement(lb_elem, "reporting_entity_role").text = lb.get("reporting_entity_role", "CREDIT_INSTITUTION")

        # Transactions
        for tx in (transactions or []):
            tx_elem = ET.SubElement(root, "transaction")
            ET.SubElement(tx_elem, "transaction_number").text = tx.get("transaction_number", f"TX-{datetime.now(UTC).timestamp()}")
            if "internal_ref_number" in tx:
                ET.SubElement(tx_elem, "internal_ref_number").text = tx["internal_ref_number"]
            if "transaction_location" in tx:
                ET.SubElement(tx_elem, "transaction_location").text = tx["transaction_location"]
            if "transaction_description" in tx:
                ET.SubElement(tx_elem, "transaction_description").text = tx["transaction_description"]

            ET.SubElement(tx_elem, "date_transaction").text = tx.get("date_transaction", datetime.now(UTC).isoformat())
            if "value_date" in tx:
                ET.SubElement(tx_elem, "value_date").text = tx["value_date"]

            ET.SubElement(tx_elem, "transmode_code").text = tx.get("transmode_code", "EFT")
            amount = float(tx.get("amount_local", 0.0))
            ET.SubElement(tx_elem, "amount_local").text = f"{amount:.2f}"
            ET.SubElement(tx_elem, "currency_code").text = tx.get("currency_code", currency_code)

            if "t_from" in tx:
                tf = ET.SubElement(tx_elem, "t_from")
                if "from_funds_code" in tx["t_from"]:
                    ET.SubElement(tf, "from_funds_code").text = tx["t_from"]["from_funds_code"]
                fa = ET.SubElement(tf, "from_account")
                from_acc = tx["t_from"].get("from_account", {})
                if "institution_name" in from_acc:
                    ET.SubElement(fa, "institution_name").text = from_acc["institution_name"]
                if "institution_code" in from_acc:
                    ET.SubElement(fa, "institution_code").text = from_acc["institution_code"]
                ET.SubElement(fa, "account").text = from_acc.get("account", "ACC_FROM_UNKNOWN")
                if "currency_code" in from_acc:
                    ET.SubElement(fa, "currency_code").text = from_acc["currency_code"]

            if "t_to" in tx:
                tt = ET.SubElement(tx_elem, "t_to")
                if "to_funds_code" in tx["t_to"]:
                    ET.SubElement(tt, "to_funds_code").text = tx["t_to"]["to_funds_code"]
                ta = ET.SubElement(tt, "to_account")
                to_acc = tx["t_to"].get("to_account", {})
                if "institution_name" in to_acc:
                    ET.SubElement(ta, "institution_name").text = to_acc["institution_name"]
                if "institution_code" in to_acc:
                    ET.SubElement(ta, "institution_code").text = to_acc["institution_code"]
                ET.SubElement(ta, "account").text = to_acc.get("account", "ACC_TO_UNKNOWN")
                if "currency_code" in to_acc:
                    ET.SubElement(ta, "currency_code").text = to_acc["currency_code"]

        raw_xml = ET.tostring(root, encoding="utf-8").decode("utf-8")
        parsed = defusedxml.minidom.parseString(raw_xml)
        pretty_xml = parsed.toprettyxml(indent="  ")

        report = cls.validate_xml(
            pretty_xml,
            RegulatoryFramework.UNODC_GOAML_4_0,
            classification=classification,
            raise_on_error=validate,
        )
        return pretty_xml, report

    @classmethod
    def generate_iso20022_pacs008_xml(
        cls,
        msg_id: str,
        debtor_iban: str,
        creditor_iban: str,
        amount: float,
        currency: str = "EUR",
        debtor_name: str = "Corporate Sender AG",
        creditor_name: str = "Beneficiary Logistics SARL",
        debtor_country: str = "DE",
        creditor_country: str = "FR",
        end_to_end_id: str | None = None,
        uetr: str | None = None,
        classification: ExportClassification = ExportClassification.PROTOTYPE_EXPORT,
        validate: bool = True,
    ) -> tuple[str, RegulatoryValidationReport]:
        """Generate ISO 20022 pacs.008.001.08 Financial Institution Customer Credit Transfer XML."""
        if amount <= 0:
            raise MissingRegulatoryFieldError("pacs.008 transaction amount must be strictly positive")

        root = ET.Element(
            "Document",
            {"xmlns": "urn:iso:std:iso:20022:tech:xsd:pacs.008.001.08"},
        )
        fitofi = ET.SubElement(root, "FIToFICstmrCdtTrf")

        grphdr = ET.SubElement(fitofi, "GrpHdr")
        ET.SubElement(grphdr, "MsgId").text = msg_id
        ET.SubElement(grphdr, "CreDtTm").text = datetime.now(UTC).isoformat()

        tx_inf = ET.SubElement(fitofi, "CdtTrfTxInf")
        pmt_id = ET.SubElement(tx_inf, "PmtId")
        ET.SubElement(pmt_id, "EndToEndId").text = end_to_end_id or f"E2E-{msg_id}"
        if uetr:
            ET.SubElement(pmt_id, "UETR").text = uetr

        amt_el = ET.SubElement(tx_inf, "IntrBkSttlmAmt", {"Ccy": currency})
        amt_el.text = f"{amount:.2f}"

        # Debtor
        dbtr = ET.SubElement(tx_inf, "Dbtr")
        ET.SubElement(dbtr, "Nm").text = debtor_name
        pstl_dbtr = ET.SubElement(dbtr, "PstlAdr")
        ET.SubElement(pstl_dbtr, "Ctry").text = debtor_country

        dbtr_acct = ET.SubElement(tx_inf, "DbtrAcct")
        dbtr_id = ET.SubElement(dbtr_acct, "Id")
        ET.SubElement(dbtr_id, "IBAN").text = debtor_iban

        # Creditor
        cdtr = ET.SubElement(tx_inf, "Cdtr")
        ET.SubElement(cdtr, "Nm").text = creditor_name
        pstl_cdtr = ET.SubElement(cdtr, "PstlAdr")
        ET.SubElement(pstl_cdtr, "Ctry").text = creditor_country

        cdtr_acct = ET.SubElement(tx_inf, "CdtrAcct")
        cdtr_id = ET.SubElement(cdtr_acct, "Id")
        ET.SubElement(cdtr_id, "IBAN").text = creditor_iban

        raw_xml = ET.tostring(root, encoding="utf-8").decode("utf-8")
        parsed = defusedxml.minidom.parseString(raw_xml)
        pretty_xml = parsed.toprettyxml(indent="  ")

        report = cls.validate_xml(
            pretty_xml,
            RegulatoryFramework.ISO_20022_PACS008,
            classification=classification,
            raise_on_error=validate,
        )
        return pretty_xml, report

    @classmethod
    def generate_iso20022_pacs002_xml(
        cls,
        msg_id: str,
        orig_msg_id: str,
        status: str = "ACTC",
        amount: float = 100.0,
        currency: str = "EUR",
        reason_code: str = "AcceptedTechnicalValidation",
        classification: ExportClassification = ExportClassification.PROTOTYPE_EXPORT,
        validate: bool = True,
    ) -> tuple[str, RegulatoryValidationReport]:
        """Generate ISO 20022 pacs.002.001.10 Payment Status Report XML."""
        root = ET.Element(
            "Document",
            {"xmlns": "urn:iso:std:iso:20022:tech:xsd:pacs.002.001.10"},
        )
        rpt = ET.SubElement(root, "FIToFIPmtStsRpt")

        grphdr = ET.SubElement(rpt, "GrpHdr")
        ET.SubElement(grphdr, "MsgId").text = msg_id
        ET.SubElement(grphdr, "CreDtTm").text = datetime.now(UTC).isoformat()

        grp_inf = ET.SubElement(rpt, "OrgnlGrpInfAndSts")
        ET.SubElement(grp_inf, "OrgnlMsgId").text = orig_msg_id
        ET.SubElement(grp_inf, "OrgnlMsgNmId").text = "pacs.008.001.08"

        tx_inf = ET.SubElement(rpt, "TxInfAndSts")
        ET.SubElement(tx_inf, "StsId").text = f"STS-{msg_id}"
        ET.SubElement(tx_inf, "OrgnlEndToEndId").text = f"E2E-{orig_msg_id}"
        ET.SubElement(tx_inf, "TxSts").text = status

        rsn_inf = ET.SubElement(tx_inf, "StsRsnInf")
        ET.SubElement(rsn_inf, "Rsn").text = reason_code

