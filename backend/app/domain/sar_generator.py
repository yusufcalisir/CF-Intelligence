# ── Regulatory Framing & Classification Enums ───────────────────────────────────

class RegulatoryFramework(StrEnum):
    """Supported electronic regulatory reporting schemas and messaging standards."""

    FINCEN_SAR_2_0 = "FinCEN_SAR_2.0"
    UNODC_GOAML_4_0 = "UNODC_goAML_v4.0"
    ISO_20022_PACS008 = "pacs.008.001.08"
    ISO_20022_PACS002 = "pacs.002.001.10"
    ISO_20022_CAMT053 = "camt.053.001.08"
    ISO_20022_PAIN001 = "pain.001.001.08"


class ExportClassification(StrEnum):
    """Regulatory framing and certification status of generated filings."""

    PROTOTYPE_EXPORT = "PROTOTYPE_EXPORT"
    SUPERVISORY_PRE_CLEARANCE = "SUPERVISORY_PRE_CLEARANCE"
    CERTIFIED_SUBMISSION = "CERTIFIED_SUBMISSION"


# ── Domain Exceptions ──────────────────────────────────────────────────────────

class RegulatoryXMLError(Exception):
    """Base exception for regulatory XML generation and schema validation failures."""


class SARSchemaValidationError(RegulatoryXMLError):
    """Raised when generated or incoming XML violates official XSD schema specifications."""


class XXEInjectionDetectedError(RegulatoryXMLError):
    """Raised when an XML External Entity (XXE) or DTD injection payload is detected."""


class MissingRegulatoryFieldError(RegulatoryXMLError):
    """Raised when statutory or mandatory regulatory reporting elements are omitted."""


# ── Validation Report Data Object ─────────────────────────────────────────────

@dataclass(frozen=True)
class RegulatoryValidationReport:
    """Immutable audit report certifying XML schema conformance and cryptographic integrity."""

    is_valid: bool
    schema_name: str
    framework: RegulatoryFramework
    classification: ExportClassification
    sha256_hash: str
    errors: list[str] = field(default_factory=list)
    warning_messages: list[str] = field(default_factory=list)
    xml_byte_count: int = 0
    framing_disclaimer: str = ""
    timestamp: str = field(default_factory=lambda: datetime.now(UTC).isoformat())

    def to_dict(self) -> dict[str, Any]:
        return {
            "is_valid": self.is_valid,
            "schema_name": self.schema_name,
            "framework": self.framework.value,
            "classification": self.classification.value,
            "sha256_hash": self.sha256_hash,
            "errors": self.errors,
            "warning_messages": self.warning_messages,
            "xml_byte_count": self.xml_byte_count,
            "framing_disclaimer": self.framing_disclaimer,
            "timestamp": self.timestamp,
        }


# ── Domain Service: SARGenerator & Schema Validator ───────────────────────────

class SARGenerator:
    """Core domain service for regulatory XML generation, XSD validation, and regulatory framing."""

    REGULATORY_PROTOTYPE_DISCLAIMER: str = (
        "SCHEMA-CONFORMING EXPORT PROTOTYPE: Generated by CF-Intelligence for supervisory sandbox evaluation, "
        "inter-bank intelligence verification, and pre-clearance under institutional dual-control governance. "
        "Not an authorized submission to financial intelligence units until certified by a designated AML compliance officer."
    )

    _schema_cache: dict[str, Any] = {}
    _cache_lock: threading.Lock = threading.Lock()

    @classmethod
    def _locate_schemas_directory(cls) -> Path:
        """Resolve the authoritative schemas directory across diverse execution environments."""
        candidates = [
            Path(__file__).resolve().parents[3] / "schemas",
            Path(__file__).resolve().parents[2] / "schemas",
            Path("backend/schemas").resolve(),
            Path("schemas").resolve(),
        ]
        for candidate in candidates:
            if candidate.exists() and candidate.is_dir():
                return candidate
        # Fallback to relative backend/schemas
        return Path("backend/schemas").resolve()

    @classmethod
    def get_schema_path(cls, framework: RegulatoryFramework | str) -> Path:
        """Resolve full filesystem path for the requested regulatory schema."""
        schemas_dir = cls._locate_schemas_directory()
        val = framework.value if isinstance(framework, RegulatoryFramework) else str(framework)

        mapping: dict[str, str] = {
            RegulatoryFramework.FINCEN_SAR_2_0.value: "FinCEN_SAR_2.0.xsd",
            RegulatoryFramework.UNODC_GOAML_4_0.value: "goAML_v4.0.xsd",
            RegulatoryFramework.ISO_20022_PACS008.value: "pacs.008.001.08.xsd",
            RegulatoryFramework.ISO_20022_PACS002.value: "pacs.002.001.10.xsd",
            RegulatoryFramework.ISO_20022_CAMT053.value: "camt.053.001.08.xsd",
            RegulatoryFramework.ISO_20022_PAIN001.value: "pain.001.001.08.xsd",
        }

        filename = mapping.get(val, f"{val}.xsd")
        schema_path = schemas_dir / filename
        if not schema_path.exists():
            # If not in candidate dir, search in parents
            alt = Path("backend/schemas") / filename
            if alt.exists():
                return alt.resolve()
            raise FileNotFoundError(f"Regulatory XSD schema not found: {filename} in {schemas_dir}")
        return schema_path

    @classmethod
    def get_compiled_schema(cls, framework: RegulatoryFramework | str) -> Any:
        """Compile and cache lxml.etree.XMLSchema instance in a thread-safe registry."""
        val = framework.value if isinstance(framework, RegulatoryFramework) else str(framework)
        with cls._cache_lock:
            if val in cls._schema_cache:
                return cls._schema_cache[val]

            schema_path = cls.get_schema_path(framework)
            try:
                from lxml import etree  # type: ignore[import-not-found,import-untyped] # nosec

                with open(schema_path, "rb") as f:
                    schema_doc = etree.XML(f.read())
                compiled = etree.XMLSchema(schema_doc)
                cls._schema_cache[val] = compiled
                logger.info("Compiled and cached regulatory XSD schema: %s", schema_path.name)
                return compiled
            except ImportError as err:
                logger.warning("lxml library not installed: skipping compiled XSD validation: %s", err)
                return None
            except Exception as exc:
                raise SARSchemaValidationError(
                    f"Failed to parse and compile regulatory XSD schema '{schema_path.name}': {exc}"
                ) from exc

    # ── Security & Integrity Guardrails ──────────────────────────────────────────

    @classmethod
    def guard_xxe(cls, xml_content: str) -> None:
        """Detect and reject XML External Entity (XXE) and Document Type Definition (DTD) injections."""
        if not xml_content or not xml_content.strip():
            raise MissingRegulatoryFieldError("XML payload is empty.")

        dangerous_patterns = [
            r"<!DOCTYPE",
            r"<!ENTITY",
            r"SYSTEM\s+[\"']",
            r"PUBLIC\s+[\"']",
        ]
        for pattern in dangerous_patterns:
            if re.search(pattern, xml_content, re.IGNORECASE):
                logger.error("XXE / DTD injection attempt detected: matched pattern '%s'", pattern)
                raise XXEInjectionDetectedError(
                    f"Forbidden XML External Entity (XXE) or DTD declaration detected: pattern '{pattern}'"
                )

    @staticmethod
    def compute_sha256(xml_content: str) -> str:
        """Compute authoritative SHA-256 hexadecimal digest of canonical XML string."""
        clean_bytes = xml_content.strip().encode("utf-8")
        return hashlib.sha256(clean_bytes).hexdigest()

    # ── Validation Engine ────────────────────────────────────────────────────────

    @classmethod
    def validate_xml(
        cls,
        xml_content: str,
        framework: RegulatoryFramework,
        classification: ExportClassification = ExportClassification.PROTOTYPE_EXPORT,
        raise_on_error: bool = False,
    ) -> RegulatoryValidationReport:
        """Validate XML string against official XSD schema and security invariants."""
        # 1. Guard against XXE
        cls.guard_xxe(xml_content)

        # 2. Syntax validation via defusedxml
        try:
            _ = DefusedET.fromstring(xml_content.encode("utf-8"))
        except Exception as exc:
            msg = f"XML syntax parsing error: {exc}"
            if raise_on_error:
                raise SARSchemaValidationError(msg) from exc
            return RegulatoryValidationReport(
                is_valid=False,
                schema_name=framework.value,
                framework=framework,
                classification=classification,
                sha256_hash=cls.compute_sha256(xml_content),
                errors=[msg],
                xml_byte_count=len(xml_content.encode("utf-8")),
                framing_disclaimer=cls.REGULATORY_PROTOTYPE_DISCLAIMER,
            )

        # 3. Formal XSD validation via compiled lxml schema
        compiled_schema = cls.get_compiled_schema(framework)
        errors: list[str] = []

        if compiled_schema is not None:
            try:
                from lxml import etree  # type: ignore[import-not-found,import-untyped] # nosec

                doc = etree.fromstring(xml_content.encode("utf-8"))
                if not compiled_schema.validate(doc):
                    errors = [
                        f"Line {err.line}, Col {err.column}: {err.message}"
                        for err in compiled_schema.error_log
                    ]
            except Exception as exc:
                errors.append(f"XSD schema evaluation failure: {exc}")

        is_valid = len(errors) == 0
        if not is_valid and raise_on_error:
            raise SARSchemaValidationError(
                f"Regulatory XML failed '{framework.value}' XSD schema validation: {'; '.join(errors)}"
            )

        return RegulatoryValidationReport(
            is_valid=is_valid,
            schema_name=framework.value,
            framework=framework,
            classification=classification,
            sha256_hash=cls.compute_sha256(xml_content),
            errors=errors,
            xml_byte_count=len(xml_content.encode("utf-8")),
            framing_disclaimer=cls.REGULATORY_PROTOTYPE_DISCLAIMER,
        )

